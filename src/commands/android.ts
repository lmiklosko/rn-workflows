import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { inspectKeystore } from '../ci/android.js';
import { UserError } from '../errors.js';
import type { GitHub } from '../github/client.js';
import { credentialsDir, requireFile, resolvePassword, resolveProfile, type CommonOptions } from './shared.js';

export interface AndroidOptions extends CommonOptions {
  generate?: boolean;
  keystore?: string;
  alias?: string;
  keystorePassword?: string;
  keyPassword?: string;
  properties?: string;
  force?: boolean;
}

export interface AndroidCredentials {
  keystore: Buffer;
  keystorePassword: string;
  keyAlias: string;
  /** Empty when the key shares the keystore password. */
  keyPassword: string;
  certSha256: string;
}

/** Reads a Java .properties file as far as signing files need: `key=value`, comments, no continuations. */
export function parseProperties(content: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const raw of content.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || line.startsWith('!')) continue;
    const match = /^([^=:\s]+)\s*[=:]?\s*(.*)$/.exec(line);
    if (match) result[match[1]!] = match[2]!.replace(/\\([\\=:#! ])/g, '$1');
  }
  return result;
}

export interface GenerateResult extends AndroidCredentials {
  keystorePath: string;
  propertiesPath: string;
}

/**
 * Creates an upload keystore and keeps a local copy with its passwords. GitHub
 * secrets cannot be read back, so this copy is the only way to recover the key.
 */
export function generateKeystore(dir: string, commonName: string): GenerateResult {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const keystorePath = path.join(dir, 'upload.keystore');
  if (fs.existsSync(keystorePath)) {
    throw new UserError(
      `${keystorePath} already exists. Import it with --keystore, or move it away before generating a new one.`,
    );
  }
  const password = randomBytes(18).toString('base64url');
  const keyAlias = 'upload';

  try {
    execFileSync(
      'keytool',
      ['-genkeypair', '-storetype', 'PKCS12', '-keystore', keystorePath, '-alias', keyAlias,
        '-keyalg', 'RSA', '-keysize', '2048', '-validity', '10000',
        '-storepass:env', 'RNW_STOREPASS', '-keypass:env', 'RNW_STOREPASS',
        '-dname', `CN=${commonName.replace(/[,+"\\<>;=]/g, ' ')}`],
      { env: { ...process.env, RNW_STOREPASS: password }, stdio: ['ignore', 'ignore', 'pipe'] },
    );
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') {
      throw new UserError('keytool was not found. Install a JDK to generate a keystore, or import an existing one with --keystore.');
    }
    throw e;
  }
  fs.chmodSync(keystorePath, 0o600);

  const { certSha256 } = inspectKeystore(keystorePath, password, keyAlias, password);
  const propertiesPath = path.join(dir, 'keystore.properties');
  fs.writeFileSync(
    propertiesPath,
    [
      '# Generated by rn-workflows. Store this file and upload.keystore in your password manager.',
      '# Losing them means losing the ability to update the app with this key.',
      'storeFile=upload.keystore',
      `storePassword=${password}`,
      `keyAlias=${keyAlias}`,
      `keyPassword=${password}`,
      `certSha256=${certSha256}`,
      '',
    ].join('\n'),
    { mode: 0o600 },
  );

  return {
    keystore: fs.readFileSync(keystorePath),
    keystorePassword: password,
    keyAlias,
    keyPassword: '',
    certSha256,
    keystorePath,
    propertiesPath,
  };
}

export async function loadExistingKeystore(options: AndroidOptions, cwd: string): Promise<AndroidCredentials> {
  let keystoreFile = options.keystore;
  let alias = options.alias;
  let storePassword = options.keystorePassword;
  let keyPassword = options.keyPassword;

  // A signing properties file, as many projects already keep, can supply everything.
  if (options.properties) {
    const file = requireFile(options.properties, 'The properties file');
    const props = parseProperties(fs.readFileSync(file, 'utf8'));
    keystoreFile ??= props.storeFile ? path.resolve(path.dirname(file), props.storeFile) : undefined;
    alias ??= props.keyAlias;
    storePassword ??= props.storePassword;
    keyPassword ??= props.keyPassword;
    if (!keystoreFile && props.storeFileBase64) {
      throw new UserError('The properties file embeds the keystore as storeFileBase64. Decode it to a file and pass --keystore.');
    }
  }

  const file = requireFile(keystoreFile, 'A keystore (--keystore, or storeFile in --properties)');
  if (!alias) throw new UserError('The key alias is required: pass --alias.');
  const resolvedStorePassword = await resolvePassword('Keystore password', storePassword, 'ANDROID_KEYSTORE_PASSWORD');
  const resolvedKeyPassword = keyPassword ?? process.env.ANDROID_KEY_PASSWORD ?? '';

  const { certSha256 } = inspectKeystore(file, resolvedStorePassword, alias, resolvedKeyPassword || resolvedStorePassword);
  void cwd;
  return {
    keystore: fs.readFileSync(file),
    keystorePassword: resolvedStorePassword,
    keyAlias: alias,
    keyPassword: resolvedKeyPassword === resolvedStorePassword ? '' : resolvedKeyPassword,
    certSha256,
  };
}

export async function uploadAndroidCredentials(github: GitHub, environment: string, creds: AndroidCredentials): Promise<void> {
  await github.ensureEnvironment(environment);
  await github.setSecrets(environment, {
    ANDROID_KEYSTORE_BASE64: creds.keystore.toString('base64'),
    ANDROID_KEYSTORE_PASSWORD: creds.keystorePassword,
    ANDROID_KEY_ALIAS: creds.keyAlias,
    ...(creds.keyPassword ? { ANDROID_KEY_PASSWORD: creds.keyPassword } : {}),
  });
  // A key password left over from a previous keystore would be tried against the new one.
  if (!creds.keyPassword) await github.deleteSecret(environment, 'ANDROID_KEY_PASSWORD');
  await github.setVariables(environment, { ANDROID_CERT_SHA256: creds.certSha256 });
}

export async function runAndroidCredentials(options: AndroidOptions, github: GitHub, cwd: string): Promise<void> {
  if (options.generate && (options.keystore || options.properties)) {
    throw new UserError('Choose one: --generate creates a new keystore, --keystore/--properties import an existing one.');
  }
  if (!options.generate && !options.keystore && !options.properties) {
    throw new UserError('Pass --generate to create a keystore, or --keystore <file> (or --properties <file>) to import one.');
  }

  const profile = resolveProfile(cwd, options.profile, options.config);
  if (!profile.known) {
    console.log(`Note: profile '${profile.name}' is not in the config file; using a GitHub Environment of the same name.`);
  }

  // Replacing the key an app is published with locks you out of updating it,
  // and the old secret cannot be read back. Make that a deliberate act.
  if (options.generate && !options.force) {
    const existing = await github.listSecrets(profile.environment).catch(() => []);
    if (existing.some((s) => s.name === 'ANDROID_KEYSTORE_BASE64')) {
      throw new UserError(
        `Environment '${profile.environment}' in ${github.slug} already has an Android keystore. ` +
          'Generating would replace it, and the current one cannot be recovered from GitHub. Pass --force if that is what you want.',
      );
    }
  }

  let creds: AndroidCredentials;
  if (options.generate) {
    const generated = generateKeystore(credentialsDir(cwd, profile.name, 'android'), `${github.repo.name} upload key`);
    creds = generated;
    console.log(`Generated a keystore: ${path.relative(cwd, generated.keystorePath)}`);
    console.log(`Passwords are in:     ${path.relative(cwd, generated.propertiesPath)}`);
    console.log('IMPORTANT: copy both files to your password manager now. GitHub will not give them back,');
    console.log('and without them you cannot sign an update for an app published with this key.');
  } else {
    creds = await loadExistingKeystore(options, cwd);
    console.log('Keystore opened with the given alias and passwords.');
  }

  await uploadAndroidCredentials(github, profile.environment, creds);
  console.log(`Android signing is set for environment '${profile.environment}' in ${github.slug}.`);
  console.log(`Signing certificate SHA-256: ${creds.certSha256}`);
}
